import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ADAPTER = path.resolve(here, '..');
export const REPO = path.resolve(ADAPTER, '..', '..');
export const SCRIPTS = path.join(ADAPTER, 'scripts');
export const HOOK = path.join(ADAPTER, 'hooks', 'session-start.mjs');
export const INTEL = path.join(REPO, 'tools', 'bin', 'project-intel.mjs');

const made = [];
export function tmp(prefix = 'erdem-adapter-') {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  made.push(d);
  return d;
}
export function cleanup() {
  for (const d of made.splice(0)) fs.rmSync(d, { recursive: true, force: true });
}

export function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

export function tree(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const abs = path.join(d, e.name);
      if (e.isDirectory()) walk(abs);
      else out.push(path.relative(dir, abs).split(path.sep).join('/'));
    }
  })(dir);
  return out.sort();
}

/** An environment that cannot reach the real user's home or Claude configuration. */
export function isolatedEnv(home, extra = {}) {
  const env = { ...process.env };
  for (const k of Object.keys(env)) if (k.startsWith('ERDEM_') || k === 'CLAUDE_CONFIG_DIR') delete env[k];
  return { ...env, HOME: home, USERPROFILE: home, CLAUDE_CONFIG_DIR: path.join(home, '.claude'), ...extra };
}

export function node(script, args = [], { env, cwd, input, timeout = 30000 } = {}) {
  return spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', env, cwd, input, timeout, windowsHide: true });
}

export function hook(project, env, stdin) {
  return node(HOOK, [], { env, cwd: project, input: stdin ?? JSON.stringify({ cwd: project, hook_event_name: 'SessionStart', source: 'startup' }) });
}

export function hasGit() {
  return spawnSync('git', ['--version'], { encoding: 'utf8' }).status === 0;
}

export function git(dir, ...args) {
  return spawnSync('git', ['-C', dir, '-c', 'user.email=t@t', '-c', 'user.name=t', ...args], { encoding: 'utf8' });
}

/** A copy of the Phase 3 app fixture with an index generated by the real engine. */
export function indexedProject({ withGit = false, profile = 'standard' } = {}) {
  const dir = tmp('erdem-proj-');
  fs.cpSync(path.join(REPO, 'tools', 'test', 'fixtures', 'app'), dir, { recursive: true });
  const r = node(INTEL, ['index', dir, '--profile', profile], { cwd: dir });
  if (r.status !== 0) throw new Error(`index failed: ${r.stderr}`);
  if (withGit) {
    git(dir, 'init', '-q');
    git(dir, 'add', '-A');
    git(dir, 'commit', '-q', '-m', 'init');
  }
  return dir;
}

export const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
