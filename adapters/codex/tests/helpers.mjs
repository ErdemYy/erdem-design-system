import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ADAPTER = path.resolve(here, '..');
export const REPO = path.resolve(ADAPTER, '..', '..');
export const SCRIPTS = path.join(ADAPTER, 'scripts');
export const INTEL = path.join(REPO, 'tools', 'bin', 'project-intel.mjs');
export const LAUNCHER = path.join(ADAPTER, 'skill', 'scripts', 'erdem.mjs');

const made = [];
export function tmp(prefix = 'erdem-codex-') {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  made.push(d);
  return d;
}
export function cleanup() {
  for (const d of made.splice(0)) fs.rmSync(d, { recursive: true, force: true });
}

export function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

export function tree(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const abs = path.join(d, e.name);
      if (e.isDirectory()) walk(abs);
      else out.push(path.relative(dir, abs).split(path.sep).join('/'));
    }
  })(dir);
  return out.sort();
}

export const snapshot = (dir) => Object.fromEntries(tree(dir).map((f) => [f, fs.readFileSync(path.join(dir, f), 'latin1')]));

/** Environment that cannot reach the real user's home or Codex configuration. */
export function isolatedEnv(home, extra = {}) {
  const env = { ...process.env };
  for (const k of Object.keys(env)) if (k.startsWith('ERDEM_') || k === 'CODEX_HOME') delete env[k];
  return { ...env, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'), ...extra };
}

export function node(script, args = [], { env, cwd, input, timeout = 60000 } = {}) {
  return spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', env, cwd, input, timeout, windowsHide: true });
}

/** A copy of the Phase 3 app fixture with an index generated by the real engine. */
export function indexedProject({ profile = 'standard', extraConfig } = {}) {
  const dir = tmp('erdem-proj-');
  fs.cpSync(path.join(REPO, 'tools', 'test', 'fixtures', 'app'), dir, { recursive: true });
  if (extraConfig) write(path.join(dir, 'project-intel.config.json'), JSON.stringify(extraConfig));
  const r = node(INTEL, ['index', dir, '--profile', profile], { cwd: dir });
  if (r.status !== 0) throw new Error(`index failed: ${r.stderr}`);
  return dir;
}

export const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));

export function capture() {
  const lines = [];
  return { io: { out: (t) => lines.push(t), err: (t) => lines.push(t) }, text: () => lines.join('\n') };
}

/** A fresh fake home (codex home and agents home included) for one test. */
export function fakeHome() {
  const root = tmp('erdem-home-');
  return { root, codexHome: path.join(root, '.codex'), agentsHome: path.join(root, '.agents'), env: isolatedEnv(root) };
}
