import path from 'node:path';
import { SCHEMA, TOOL } from '../lib/constants.mjs';
import { cmp, countBy, isUnder, pluralize } from '../lib/util.mjs';

/** Markdown rendering for AI_INDEX.md, DIRECTORY_INDEX.md and FILE_INDEX.md. Concise by construction. */

const FRAMEWORK_HINTS = {
  next: 'Next.js', react: 'React', vue: 'Vue', svelte: 'Svelte', '@sveltejs/kit': 'SvelteKit', nuxt: 'Nuxt', astro: 'Astro',
  express: 'Express', vite: 'Vite', tailwindcss: 'Tailwind CSS', typescript: 'TypeScript', three: 'three.js',
  '@react-three/fiber': 'React Three Fiber', gsap: 'GSAP', electron: 'Electron', 'react-native': 'React Native', expo: 'Expo',
};
const LOCKFILES = { 'package-lock.json': 'npm', 'pnpm-lock.yaml': 'pnpm', 'yarn.lock': 'yarn', 'bun.lockb': 'bun' };
const ROLE_TEXT = {
  'package-entry': 'package entry', 'framework-route': 'framework route', 'shared-module': 'shared module',
  'global-config': 'global configuration', configured: 'configured public surface', 'configured-entry': 'configured entry point',
};

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';
const fpText = (fp) => (fp?.hash ? `${fp.algo}:${fp.hash}` : 'unverifiable');
const short = (fp) => (fp?.hash ? fp.hash.slice(0, 12) : 'unverifiable');

export function frontMatter(fields) {
  return '---\n' + Object.entries(fields).map(([k, v]) => `${k}: ${v}`).join('\n') + '\n---\n';
}

export function parseFrontMatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) out[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return out;
}

export function roleOf(node) {
  if (node.type !== 'file') return '';
  const m = node.metadata;
  if (m.category === 'test') return 'test file';
  const parts = [];
  if (m.entryPoint) parts.push('entry point');
  for (const r of m.publicSurfaceReasons) parts.push(ROLE_TEXT[r] ?? r);
  if (!parts.length) parts.push(node.consumers.length ? 'internal module' : m.dependencyAnalysis === 'analyzed' ? 'leaf module' : 'file');
  return [...new Set(parts)].join(', ');
}

function table(header, rows) {
  if (!rows.length) return '_none_\n';
  const line = (cells) => `| ${cells.map(cell).join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n') + '\n';
}

function meta(common) {
  return frontMatter({
    generatedAt: common.generatedAt,
    source: `${TOOL.name} ${TOOL.version}`,
    scope: common.scope,
    ...(common.path ? { path: common.path } : {}),
    schemaVersion: SCHEMA.index,
    fingerprint: fpText(common.fingerprint),
    generated: 'true',
  });
}

const GENERATED_NOTE = '<!-- Generated by project-intel. Navigation aid, not source of truth. Do not edit by hand: changes are overwritten. Source code wins. -->\n';

/** Subsystem dependency summary: top neighbors by edge count. */
function subsystemLinks(graph) {
  const subOf = new Map(graph.nodes.filter((n) => n.type === 'file').map((n) => [n.id, n.metadata.subsystem]));
  const out = new Map();
  const into = new Map();
  for (const e of graph.edges) {
    const a = subOf.get(e.source);
    const b = subOf.get(e.target);
    if (!a || !b || a === b) continue;
    if (!out.has(a)) out.set(a, new Map());
    out.get(a).set(b, (out.get(a).get(b) ?? 0) + 1);
    if (!into.has(b)) into.set(b, new Map());
    into.get(b).set(a, (into.get(b).get(a) ?? 0) + 1);
  }
  const top = (m, k) => (m ? [...m.entries()].sort((x, y) => y[1] - x[1] || cmp(x[0], y[0])).slice(0, 3).map(([key]) => key).join(', ') : '');
  return { dependsOn: (k) => top(out.get(k)), usedBy: (k) => top(into.get(k)) };
}

export function renderAiIndex(ctx) {
  const { scan, graph, cfg, profile, important, artifacts, now, directoryIndexPaths } = ctx;
  const rootPkg = scan.packages.get('package.json');
  const fileNodes = graph.nodes.filter((n) => n.type === 'file');
  const sources = fileNodes.filter((n) => n.metadata.category === 'source');
  const tests = fileNodes.filter((n) => n.metadata.category === 'test');
  const subsystems = Object.entries(countBy(sources, (n) => n.metadata.subsystem)).sort((a, b) => b[1] - a[1] || cmp(a[0], b[0]));
  const links = subsystemLinks(graph);
  const langs = Object.entries(scan.stats.byLanguage).sort((a, b) => b[1] - a[1] || cmp(a[0], b[0])).slice(0, 6);
  const deps = new Set(rootPkg?.dependencies ?? []);
  const hints = Object.entries(FRAMEWORK_HINTS).filter(([d]) => deps.has(d)).map(([, label]) => label).slice(0, 8);
  const lock = scan.files.map((f) => LOCKFILES[path.posix.basename(f.path)]).filter(Boolean);
  const entries = fileNodes.filter((n) => n.metadata.entryPoint).map((n) => n.id).sort(cmp);
  const stateFiles = ['DECISIONS.md', 'TASK_STATE.md', 'HANDOFF.md'].map((name) => [name, scan.files.filter((f) => path.posix.basename(f.path) === name).map((f) => f.path)]);
  const visibleIgnored = scan.ignored.filter((i) => i.reason !== 'output');
  const generatedDirs = visibleIgnored.filter((i) => /(^|\/)(generated|__generated__)\/$/.test(i.path)).map((i) => i.path);
  const ignoredNames = [...new Set(visibleIgnored.map((i) => i.path))].slice(0, 15);
  const analyzed = graph.stats.languagesAnalyzed;
  const metaOnly = Object.entries(graph.stats.languagesMetadataOnly).map(([l, c]) => `${l} (${pluralize(c, 'file')})`);

  return build();

  function build() {
    const lines = [];
    lines.push(
      frontMatter({
        generatedAt: now,
        source: `${TOOL.name} ${TOOL.version}`,
        scope: 'project',
        schemaVersion: SCHEMA.index,
        fingerprint: fpText(graph.fingerprint),
        indexProfile: profile,
        configDigest: scan.configDigest.slice(0, 16),
        generated: 'true',
      }),
    );
    lines.push(GENERATED_NOTE);
    lines.push(`# AI Index: ${cell(graph.project.name)}\n`);
    lines.push('## Identity\n');
    lines.push(`- Name: ${code(graph.project.name)}${rootPkg?.description ? ` — ${cell(rootPkg.description)}` : ''}`);
    lines.push(`- Languages (files): ${langs.map(([l, c]) => `${l} ${c}`).join(', ') || 'none detected'}`);
    if (hints.length) lines.push(`- Dependency hints (from the root manifest): ${hints.join(', ')}`);
    if (lock.length) lines.push(`- Package manager (from lockfile): ${[...new Set(lock)].join(', ')}`);
    lines.push(`- Index profile: ${profile}\n`);

    lines.push('## Architecture overview\n');
    lines.push(
      `${pluralize(sources.length, 'source file')} and ${pluralize(tests.length, 'test file')} in ${pluralize(subsystems.length, 'subsystem')}; ` +
        `${pluralize(graph.stats.edges, 'dependency edge')} among files and packages, ${pluralize(graph.stats.cycles, 'dependency cycle')}, ` +
        `${pluralize(fileNodes.filter((n) => n.publicSurface).length, 'public surface')}.`,
    );
    lines.push(`Dependency analysis: ${analyzed.length ? analyzed.join(', ') : 'none'}${metaOnly.length ? `; metadata only: ${metaOnly.join(', ')}` : ''}.\n`);
    lines.push(table(['Subsystem', 'Source files', 'Depends on', 'Used by'], subsystems.slice(0, 15).map(([k, c]) => [code(k), c, links.dependsOn(k), links.usedBy(k)])));
    if (subsystems.length > 15) lines.push(`${subsystems.length - 15} more subsystems are in ${code(`${cfg.outputDir}/graph/graph.json`)}.\n`);

    lines.push('## Important directories\n');
    lines.push(
      table(
        ['Path', 'Source files (recursive)', 'Why', 'Local index'],
        important.dirs.slice(0, 15).map((d) => [code(d.path), d.sourceFiles, d.reasons.join(', '), directoryIndexPaths.get(d.path) ? code(directoryIndexPaths.get(d.path)) : '']),
      ),
    );

    lines.push('## Important files\n');
    lines.push(table(['Path', 'Why', 'Risk'], important.files.slice(0, 20).map((f) => [code(f.id), f.reasons.join(', '), f.risk ?? 'unknown'])));

    lines.push('## Entry points\n');
    lines.push(entries.length ? entries.slice(0, 15).map((e) => `- ${code(e)}`).join('\n') + '\n' : '_none detected_\n');

    lines.push('## Generated and ignored areas\n');
    lines.push(`- Generated folders present: ${generatedDirs.length ? generatedDirs.map(code).join(', ') : 'none'}`);
    lines.push(`- Not read by default (present): ${ignoredNames.length ? ignoredNames.map(code).join(', ') : 'none'}`);
    lines.push(`- Secret-pattern files withheld (never read): ${scan.withheld.length}\n`);

    lines.push('## Decisions, task state, handoff\n');
    for (const [name, found] of stateFiles) lines.push(`- ${name}: ${found.length ? found.map(code).join(', ') : 'none found'}`);
    lines.push('');

    lines.push('## Derived artifacts (state at generation: current)\n');
    lines.push(table(['Path', 'Kind', 'Schema'], artifacts.map((a) => [code(`${cfg.outputDir}/${a.path}`), a.kind, a.schema ?? ''])));
    lines.push(`Check freshness with ${code('project-intel status')}. If this index disagrees with the code, the code wins.\n`);

    lines.push('## Index metadata\n');
    lines.push(`- Generated by ${TOOL.name} ${TOOL.version} (timestamp in the front matter)`);
    lines.push(`- Hash: ${scan.hashAlgo}, text normalized (LF, no BOM); structure fingerprint ${fpText(graph.fingerprint).slice(0, 24)}…`);
    lines.push(`- Files indexed: ${scan.stats.files}; configuration digest ${scan.configDigest.slice(0, 12)}`);
    return lines.join('\n');
  }
}

export function renderDirectoryIndex(ctx) {
  const { dir, graph, scan, cfg, now, important, fingerprint, viewPath, members, hint, relatedDocs } = ctx;
  const memberIds = new Set(members.map((n) => n.id));
  const subOf = (id) => graph.nodes.find((n) => n.id === id)?.metadata?.subsystem ?? id;
  const depTargets = new Map();
  const consumerSources = new Map();
  const externals = new Map();
  const nodeMap = new Map(graph.nodes.map((n) => [n.id, n]));
  for (const e of graph.edges) {
    const sIn = memberIds.has(e.source);
    const tIn = memberIds.has(e.target);
    if (sIn && !tIn) {
      const t = nodeMap.get(e.target);
      if (t?.type === 'external') externals.set(t.metadata.package, (externals.get(t.metadata.package) ?? 0) + 1);
      else depTargets.set(subOf(e.target), (depTargets.get(subOf(e.target)) ?? 0) + 1);
    } else if (!sIn && tIn) {
      const s = nodeMap.get(e.source);
      if (s?.type === 'file') consumerSources.set(s.metadata.subsystem, (consumerSources.get(s.metadata.subsystem) ?? 0) + 1);
    }
  }
  const top = (m, n = 10) => [...m.entries()].sort((a, b) => b[1] - a[1] || cmp(a[0], b[0])).slice(0, n);
  const sources = members.filter((n) => n.metadata.category === 'source');
  const testsCount = members.filter((n) => n.metadata.category === 'test').length;
  const langs = Object.entries(countBy(sources, (n) => n.language ?? 'unknown')).sort((a, b) => b[1] - a[1]);
  const importantHere = important.files.filter((f) => isUnder(f.id, dir));
  const entries = members.filter((n) => n.metadata.entryPoint).map((n) => n.id).sort(cmp);
  const interfaceFiles = members
    .filter((n) => n.metadata.category !== 'test' && n.consumers.some((c) => !memberIds.has(c) && nodeMap.get(c)?.metadata?.category !== 'test'))
    .sort((a, b) => b.consumers.length - a.consumers.length || cmp(a.id, b.id))
    .slice(0, 10);
  const analysisAvailable = members.some((n) => n.metadata.dependencyAnalysis === 'analyzed' || n.metadata.dependencyAnalysis === 'partial');

  const L = [];
  L.push(meta({ generatedAt: now, scope: 'directory', path: dir, fingerprint }));
  L.push(GENERATED_NOTE);
  L.push(`# Directory Index: ${code(dir)}\n`);
  L.push('## Purpose\n');
  L.push(hint ? `${cell(hint)}\n` : '_Not determined by tooling (no README or package description found)._\n');
  L.push('## Composition\n');
  L.push(`${pluralize(sources.length, 'source file')}${langs.length ? ` (${langs.map(([l, c]) => `${l} ${c}`).join(', ')})` : ''}, ${pluralize(testsCount, 'test file')}.\n`);
  L.push('## Important files\n');
  L.push(table(['Path', 'Why', 'Risk'], importantHere.map((f) => [code(f.id), f.reasons.join(', '), f.risk ?? 'unknown'])));
  L.push('## Entry points\n');
  L.push(entries.length ? entries.map((e) => `- ${code(e)}`).join('\n') + '\n' : '_none_\n');
  L.push('## Responsibilities (derived)\n');
  L.push('Files used from outside this directory form its interface to the rest of the project.\n');
  L.push(table(['File', 'Used by', 'Exports'], interfaceFiles.map((n) => [code(n.id), n.consumers.length, n.exports.slice(0, 6).join(', ')])));
  L.push('## Dependencies\n');
  L.push(analysisAvailable ? table(['Depends on', 'Edges'], [...top(depTargets).map(([k, c]) => [code(k), c]), ...top(externals, 8).map(([k, c]) => [`${code(k)} (package)`, c])]) : '_No dependency analysis for the languages in this directory._\n');
  L.push('## Consumers\n');
  L.push(analysisAvailable || consumerSources.size ? table(['Used by', 'Edges'], top(consumerSources).map(([k, c]) => [code(k), c])) : '_Not known: no dependency analysis for the languages in this directory._\n');
  L.push('## Local constraints\n');
  L.push('_None recorded by tooling. Hand-written constraints belong in project documentation._\n');
  L.push('## Related docs\n');
  L.push(relatedDocs.length ? relatedDocs.map((d) => `- ${code(d)}`).join('\n') + '\n' : '_none_\n');
  if (viewPath) L.push(`## Graph view\n\n- ${code(`${cfg.outputDir}/${viewPath}`)}\n`);
  void scan;
  return L.join('\n');
}

export function renderFileIndex(ctx) {
  const { graph, important, now, summaryPaths, cfg } = ctx;
  const nodeMap = new Map(graph.nodes.map((n) => [n.id, n]));
  const rows = important.files.map((f) => {
    const n = nodeMap.get(f.id);
    const tests = n.consumers.filter((c) => nodeMap.get(c)?.metadata?.category === 'test').slice(0, 3);
    const deps = n.imports.filter((i) => nodeMap.get(i)?.type === 'file');
    return [
      code(n.id),
      roleOf(n),
      n.exports.slice(0, 8).join(', '),
      deps.length,
      n.consumers.filter((c) => nodeMap.get(c)?.metadata?.category !== 'test').length,
      tests.map(code).join(', '),
      n.language ?? '',
      summaryPaths.get(n.id) ? code(`${cfg.outputDir}/${summaryPaths.get(n.id)}`) : '',
      short(n.fingerprint),
    ];
  });
  const L = [];
  L.push(meta({ generatedAt: now, scope: 'project', fingerprint: graph.fingerprint }));
  L.push(GENERATED_NOTE);
  L.push('# File Index\n');
  L.push('Important files only. Public API is the list of exported names found by static analysis, not a specification.\n');
  L.push(table(['Path', 'Role', 'Public API', 'Deps', 'Consumers', 'Tests', 'Language', 'Summary', 'Fingerprint'], rows));
  return L.join('\n');
}
