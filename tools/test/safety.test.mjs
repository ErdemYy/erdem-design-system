import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { runIndex, runStatus } from '../lib/pipeline.mjs';
import { cleanup, listTree, makeTree } from './helpers.mjs';

after(cleanup);

const SECRET = 'SUPERSECRET123';

function secretProject() {
  return makeTree({
    'package.json': '{ "name": "safe", "main": "src/index.ts" }',
    'src/index.ts': "import { cfg } from './config';\nexport const run = () => cfg;\n",
    'src/config.ts': `// Loads settings. The value below is a placeholder, not a secret.\nexport const cfg = { mode: 'dev' };\n`,
    '.env': `API_KEY=${SECRET}`,
    '.env.local': `TOKEN=${SECRET}`,
    '.env.example': `API_KEY=${SECRET}`,
    'keys/server.pem': `-----BEGIN PRIVATE KEY-----\n${SECRET}\n`,
    'config/credentials.json': `{"password":"${SECRET}"}`,
    'deploy/id_rsa': SECRET,
    '.npmrc': `//registry.npmjs.org/:_authToken=${SECRET}`,
  });
}

test('secret values never appear in any generated artifact, and secret files are never opened', () => {
  const dir = secretProject();
  const opened = [];
  const original = fs.readFileSync;
  fs.readFileSync = function patched(file, ...rest) {
    opened.push(String(file).replace(/\\/g, '/'));
    return original.call(this, file, ...rest);
  };
  try {
    runIndex(dir, { profile: 'full' });
    runStatus(dir);
  } finally {
    fs.readFileSync = original;
  }
  for (const secret of ['/.env', '.env.local', '.env.example', 'server.pem', 'credentials.json', 'id_rsa', '.npmrc']) {
    assert.ok(!opened.some((p) => p.endsWith(secret)), `${secret} must never be opened`);
  }
  assert.ok(opened.some((p) => p.endsWith('src/index.ts')), 'the spy observes ordinary reads');

  for (const rel of listTree(path.join(dir, '.ai'))) {
    const text = fs.readFileSync(path.join(dir, '.ai', rel), 'utf8');
    assert.ok(!text.includes(SECRET), `${rel} contains a secret value`);
  }
  const report = JSON.parse(fs.readFileSync(path.join(dir, '.ai/state/report.json'), 'utf8'));
  const withheld = report.withheld.map((w) => w.path);
  for (const p of ['.env', '.env.local', '.env.example', 'keys/server.pem', 'config/credentials.json', 'deploy/id_rsa', '.npmrc']) assert.ok(withheld.includes(p), `${p} existence is recorded`);
  const index = JSON.parse(fs.readFileSync(path.join(dir, '.ai/index.json'), 'utf8'));
  assert.ok(!index.files.some((f) => /\.env|\.pem|credentials|id_rsa|\.npmrc/.test(f.path)), 'withheld files are not in the file index and have no hash');
  const aiIndex = fs.readFileSync(path.join(dir, '.ai/AI_INDEX.md'), 'utf8');
  assert.match(aiIndex, /Secret-pattern files withheld \(never read\): 7/);
});

test('an existing secret never makes status stale or unverifiable', () => {
  const dir = secretProject();
  runIndex(dir, { profile: 'lite' });
  fs.writeFileSync(path.join(dir, '.env'), 'API_KEY=changed');
  assert.equal(runStatus(dir).status.ok, true, 'withheld files are outside the index; changing them is not a change of indexed content');
});

test('generated output is identifiable, versioned and separated from source', () => {
  const dir = secretProject();
  runIndex(dir, { profile: 'full' });
  const md = fs.readFileSync(path.join(dir, '.ai/AI_INDEX.md'), 'utf8');
  assert.match(md, /^---\ngeneratedAt: /);
  assert.match(md, /source: project-intel 0\.1\.0/);
  assert.match(md, /schemaVersion: 1/);
  assert.match(md, /Generated by project-intel\./);
  assert.ok(listTree(dir).filter((f) => !f.startsWith('.ai/')).every((f) => !/AI_INDEX|FILE_INDEX|DIRECTORY_INDEX/.test(f)), 'no generated index leaks into source directories');
});

test('the output directory cannot escape the project', () => {
  const dir = makeTree({ 'a.ts': 'export {}\n' });
  assert.throws(() => runIndex(dir, { overrides: { outputDir: '../escape' } }), /outputDir/);
  assert.throws(() => runIndex(dir, { overrides: { outputDir: '/abs/path' } }), /outputDir/);
  const ok = runIndex(dir, { overrides: { outputDir: 'tooling/generated-ai' }, profile: 'lite' });
  assert.equal(ok.report.outputDir, 'tooling/generated-ai');
  assert.ok(fs.existsSync(path.join(dir, 'tooling/generated-ai/AI_INDEX.md')));
});

test('previously generated output is never scanned as project content', () => {
  const dir = makeTree({ 'src/a.ts': 'export const a = 1;\n' });
  runIndex(dir, { profile: 'full' });
  const second = runIndex(dir, { profile: 'full' });
  assert.ok(!second.scan.files.some((f) => f.path.startsWith('.ai/')));
  assert.equal(second.scan.stats.files, 1);
});

test('large files are never read as source and never fail the run', () => {
  const dir = makeTree({
    'src/ok.ts': 'export const ok = 1;\n',
    'src/huge.ts': 'export const h = "' + 'x'.repeat(5000) + '";\n',
  });
  fs.writeFileSync(path.join(dir, 'project-intel.config.json'), JSON.stringify({ maxHashBytes: 1000, maxParseBytes: 500 }));
  const reads = [];
  const original = fs.readFileSync;
  fs.readFileSync = function patched(file, ...rest) {
    reads.push(String(file).replace(/\\/g, '/'));
    return original.call(this, file, ...rest);
  };
  let result;
  try {
    result = runIndex(dir, { profile: 'full' });
  } finally {
    fs.readFileSync = original;
  }
  assert.ok(!reads.some((r) => r.endsWith('src/huge.ts')), 'a file above the hash limit is not read at all');
  const node = result.graph.nodes.find((n) => n.id === 'src/huge.ts');
  assert.equal(node.fingerprint.hash, null);
  assert.equal(node.fingerprint.reason, 'too-large');
});

test('every failure is recorded with path, parser and severity; nothing is skipped silently', () => {
  const dir = makeTree({
    'good.ts': 'export const g = 1;\n',
    'unclosed.ts': 'export const a = { b: [1, 2\n/* oops',
    'binary.ts': Buffer.from([0, 1, 2, 3, 0, 0]),
    'user.ts': "import './missing-file';\n",
  });
  const r = runIndex(dir, { profile: 'lite' });
  const report = JSON.parse(fs.readFileSync(path.join(dir, '.ai/state/report.json'), 'utf8'));
  const by = (code) => report.diagnostics.filter((d) => d.code === code);
  for (const d of report.diagnostics) {
    assert.ok(d.severity && d.code && d.message, JSON.stringify(d));
    assert.ok('path' in d && ('parser' in d), JSON.stringify(d));
  }
  assert.ok(by('unterminated-comment').some((d) => d.path === 'unclosed.ts' && d.severity === 'error' && d.parser === 'javascript'));
  assert.ok(by('binary-content').some((d) => d.path === 'binary.ts' && d.severity === 'error'));
  assert.ok(by('unresolved-import').some((d) => d.path === 'user.ts' && d.severity === 'warning'));
  assert.equal(r.graph.nodes.some((n) => n.id === 'good.ts'), true, 'the rest of the project is still indexed');
});
